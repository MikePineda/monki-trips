const require = createRequire(join(WEB, 'package.json'))

/** The inner shapes of one lucide-static icon file. */
function readIcon(name) {
  const path = require.resolve(`lucide-static/icons/${name}.svg`)
  const svg = readFileSync(path, 'utf8')
  const inner = /<svg[^>]*>([\s\S]*?)<\/svg>/.exec(svg)?.[1]
  if (!inner) {
    throw new Error(`lucide icon "${name}" has no <svg> body`)
  }
  return inner
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean)
    .join('')
}

export function buildSprite(names = ICONS) {
  const symbols = names.map(
    (name) =>
      `<symbol id="${name}" viewBox="0 0 24 24" fill="none" stroke="currentColor" ` +
      `stroke-width="${STROKE_WIDTH}" stroke-linecap="round" stroke-linejoin="round">${readIcon(name)}</symbol>`
  )
  return (
    '<?xml version="1.0" encoding="UTF-8"?>\n' +
    '<!-- Generated by scripts/build-icon-sprite.mjs from lucide-static (ISC). Do not edit. -->\n' +
    `<svg xmlns="http://www.w3.org/2000/svg">\n${symbols.join('\n')}\n</svg>\n`
  )
}

export function buildNames(names = ICONS) {
  return (
    '/** Generated by scripts/build-icon-sprite.mjs. Do not edit: add the icon there. */\n' +
    'export const ICON_NAMES = [\n' +
    names.map((name) => `  '${name}',`).join('\n') +
    '\n] as const\n\n' +
    'export type IconName = (typeof ICON_NAMES)[number]\n'
  )
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]
if (isMain) {
  const sorted = [...ICONS].sort()
  if (sorted.join() !== ICONS.join()) {
    throw new Error('ICONS must be alphabetical')
  }
  mkdirSync(dirname(SPRITE_OUT), { recursive: true })
  mkdirSync(dirname(NAMES_OUT), { recursive: true })
  writeFileSync(SPRITE_OUT, buildSprite())
  writeFileSync(NAMES_OUT, buildNames())
  console.log(`icon sprite: ${ICONS.length} icons -> ${SPRITE_OUT}`)
}
